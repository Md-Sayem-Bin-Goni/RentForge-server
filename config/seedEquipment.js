async function seedEquipmentIfNeeded() {
  try {
    const count = await equipmentCollection.countDocuments();
    if (count === 0) {
      console.log('Seeding initial equipment catalog to MongoDB...');
      const docs = initialEquipmentList.map(item => ({
        ...item,
        _id: new ObjectId(),
      }));
      const result = await equipmentCollection.insertMany(docs);
      console.log(`Successfully seeded ${result.insertedCount} equipment items to MongoDB.`);
      return result;
    } else {
      console.log(`Equipment collection already contains ${count} items. Skipping auto-seed.`);
    }
  } catch (error) {
    console.error('Failed to seed equipment collection:', error.message);
  }
}

